// Package ledger implements a double-entry ledger for Pix payment events.
//
// Every transaction is a set of entries whose amounts sum to zero: money is
// never created or destroyed, it only moves between accounts. Amounts are
// stored in cents (int64) to avoid floating point errors.
package ledger

import (
	"errors"
	"fmt"
	"strings"
	"time"
)

// EventType is the kind of payment event received from the PSP / payment API.
type EventType string

const (
	// EventPixSettled is emitted when a Pix transfer is settled by the Central Bank (SPI).
	EventPixSettled EventType = "pix.settled"
	// EventPixRefunded is emitted when a settled Pix is returned (devolução).
	EventPixRefunded EventType = "pix.refunded"
)

// Sentinel errors used across the service.
var (
	ErrDuplicate      = errors.New("ledger: transaction already recorded")
	ErrInvalidEvent   = errors.New("ledger: invalid payment event")
	ErrUnbalanced     = errors.New("ledger: entries do not sum to zero")
	ErrUnknownAccount = errors.New("ledger: unknown account")
)

// PaymentEvent is the message consumed from Kafka (topic payments.events) or
// posted to the HTTP API.
type PaymentEvent struct {
	EventID      string    `json:"event_id"`
	Type         EventType `json:"type"`
	EndToEndID   string    `json:"end_to_end_id"`
	PayerAccount string    `json:"payer_account"`
	PayeeAccount string    `json:"payee_account"`
	AmountCents  int64     `json:"amount_cents"`
	OccurredAt   time.Time `json:"occurred_at"`
}

// Validate checks the business rules of a payment event.
func (e PaymentEvent) Validate() error {
	var problems []string
	if strings.TrimSpace(e.EventID) == "" {
		problems = append(problems, "event_id is required")
	}
	if e.Type != EventPixSettled && e.Type != EventPixRefunded {
		problems = append(problems, fmt.Sprintf("unsupported type %q", e.Type))
	}
	if strings.TrimSpace(e.EndToEndID) == "" {
		problems = append(problems, "end_to_end_id is required")
	}
	if e.PayerAccount == "" || e.PayeeAccount == "" {
		problems = append(problems, "payer_account and payee_account are required")
	}
	if e.PayerAccount != "" && e.PayerAccount == e.PayeeAccount {
		problems = append(problems, "payer_account and payee_account must differ")
	}
	if e.AmountCents <= 0 {
		problems = append(problems, "amount_cents must be positive")
	}
	if e.OccurredAt.IsZero() {
		problems = append(problems, "occurred_at is required")
	}
	if len(problems) > 0 {
		return fmt.Errorf("%w: %s", ErrInvalidEvent, strings.Join(problems, "; "))
	}
	return nil
}

// Entry is one leg of a transaction. Positive amounts are credits, negative
// amounts are debits.
type Entry struct {
	AccountID   string
	AmountCents int64
}

// Transaction groups the entries generated by a single payment event.
type Transaction struct {
	ID         string // the event ID: makes processing idempotent
	Type       EventType
	EndToEndID string
	Entries    []Entry
	OccurredAt time.Time
}

// FromEvent converts a payment event into a balanced double-entry transaction.
// A settlement moves money from payer to payee; a refund moves it back.
func FromEvent(e PaymentEvent) (Transaction, error) {
	if err := e.Validate(); err != nil {
		return Transaction{}, err
	}
	from, to := e.PayerAccount, e.PayeeAccount
	if e.Type == EventPixRefunded {
		from, to = to, from
	}
	tx := Transaction{
		ID:         e.EventID,
		Type:       e.Type,
		EndToEndID: e.EndToEndID,
		OccurredAt: e.OccurredAt.UTC(),
		Entries: []Entry{
			{AccountID: from, AmountCents: -e.AmountCents},
			{AccountID: to, AmountCents: e.AmountCents},
		},
	}
	return tx, tx.CheckBalanced()
}

// CheckBalanced enforces the double-entry invariant.
func (t Transaction) CheckBalanced() error {
	if len(t.Entries) < 2 {
		return fmt.Errorf("%w: at least two entries are required", ErrUnbalanced)
	}
	var sum int64
	for _, en := range t.Entries {
		sum += en.AmountCents
	}
	if sum != 0 {
		return fmt.Errorf("%w: sum is %d", ErrUnbalanced, sum)
	}
	return nil
}

// AmountCents returns the absolute amount moved by the transaction.
func (t Transaction) AmountCents() int64 {
	for _, en := range t.Entries {
		if en.AmountCents > 0 {
			return en.AmountCents
		}
	}
	return 0
}
